    clean_df["year"] = clean_df["order_date"].dt.year
    clean_df["month"] = clean_df["order_date"].dt.month
    clean_df["quarter"] = clean_df["order_date"].dt.to_period("Q").astype(str)
    
    # Sort chronologically
    clean_df = clean_df.sort_values("order_date").reset_index(drop=True)
    clean_df.to_csv(CLEAN_CSV_PATH, index=False)
    print(f"[OK] Cleaned sales dataset saved to {CLEAN_CSV_PATH}")
    
    print("Generating website traffic and conversion funnel dataset...")
    traffic_df = generate_traffic_and_funnel(clean_df)
    
    print("Building Star Schema SQLite database...")
    create_sqlite_database(clean_df, traffic_df)
    
    print("\n--- SYNTHETIC DATA GENERATION SUMMARY ---")
    completed = clean_df[clean_df["order_status"] == "Completed"]
    print(f"Total Orders Generated: {len(clean_df):,}")
    print(f"Completed Orders: {len(completed):,}")
